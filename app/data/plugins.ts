export type Scale = "Simple" | "Standard" | "Advanced" | "Large";
export type PluginStatus =
  "Public" | "Private" | "Security Hold" | "Availability Paused";

export type Plugin = {
  slug: string;
  name: string;
  aliases: string[];
  category: string;
  scale: Scale;
  beta: boolean;
  status: PluginStatus;
  summary: string;
  tags: string[];
  features: string[];
  setup: string[];
  commands: string[];
  permissions: string[];
  workflows: string[];
  config: Record<string, string[]>;
  mechanics: string[];
  examples: string[];
  limits: string[];
  dependencies: string[];
  github?: string;
  attribution?: string;
  requestable?: boolean;
};

type Seed = Omit<
  Partial<Plugin>,
  "slug" | "name" | "category" | "scale" | "summary"
> &
  Pick<Plugin, "slug" | "name" | "category" | "scale" | "summary">;

const gh = (repo: string) => `https://github.com/Luna-Hook/${repo}`;
const paperSetup = [
  "Stop the server, place the reviewed JAR in the plugins folder, then start Paper.",
  "Review the generated configuration before opening the feature to players.",
  "Grant only the permissions listed below and validate the workflow on a test server first.",
];

const make = (seed: Seed): Plugin => ({
  aliases: [],
  beta: false,
  status: "Public",
  tags: [],
  requestable: true,
  features: [
    seed.summary,
    ...(seed.workflows ?? []).slice(0, 2),
    ...(seed.mechanics ?? []).slice(0, 2),
  ],
  setup: paperSetup,
  commands: ["No player command is required for the core mechanic."],
  permissions: ["No permission nodes are declared for the core mechanic."],
  workflows: [
    "Install, configure, test with synthetic data, then enable for the intended player or staff group.",
  ],
  config: {
    settings: ["Review every generated setting before production use."],
    messages: [
      "Player-facing text is configurable where supplied by the plugin.",
    ],
  },
  mechanics: [seed.summary],
  examples: [
    "Use a disposable Paper server to confirm the configured behavior before production rollout.",
  ],
  limits: [
    "Source-reviewed behavior is documented here; live compatibility and load limits still require server testing.",
  ],
  dependencies: ["Paper"],
  ...seed,
});

